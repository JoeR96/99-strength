// Draw the app icon (the OSRS Strength skill icon over a yellow 99) into public/favicon.svg.
// Then run make-pwa-icons.mjs to render the PNGs. Run with cwd = the A2S.Web folder.
import fs from 'node:fs';
import path from 'node:path';

const GRID = 48;

// The Strength skill icon from the OSRS Wiki (Strength_icon_(detail).png, 32x44)
const SPRITE = fs.readFileSync(path.join(import.meta.dirname, 'strength-icon.png')).toString('base64');

// Stone skill-tab panel
const STONE = '#4f4434';
const STONE_DARK = '#2b241a';
const STONE_LIGHT = '#6e604a';

// Level digits, the skill tab's yellow with a black drop shadow
const NINE = ['.XXX.', 'X...X', 'X...X', '.XXXX', '....X', 'X...X', '.XXX.'];
const DIGIT_YELLOW = '#ffff00';

const rects = [];
const px = (x, y, w, h, fill) => rects.push(`<rect x="${x}" y="${y}" width="${w}" height="${h}" fill="${fill}"/>`);

function art(rows, ox, oy, scale, colourOf) {
  rows.forEach((row, y) =>
    [...row].forEach((ch, x) => {
      const fill = colourOf(ch);
      if (fill) px(ox + x * scale, oy + y * scale, scale, scale, fill);
    }),
  );
}

// Panel with a bevel: light top/left, dark bottom/right
px(0, 0, GRID, GRID, STONE_DARK);
px(1, 1, GRID - 2, GRID - 2, STONE_LIGHT);
px(2, 2, GRID - 3, GRID - 3, STONE_DARK);
px(2, 2, GRID - 4, GRID - 4, STONE);

rects.push(
  `<image x="14" y="3" width="20" height="27.5" preserveAspectRatio="none" style="image-rendering:pixelated" href="data:image/png;base64,${SPRITE}"/>`,
);

const digitsX = 13;
const digitsY = 32;
const scale = 2;
for (const [colour, dx] of [
  ['#000000', 1],
  [DIGIT_YELLOW, 0],
]) {
  art(NINE, digitsX + dx, digitsY + dx, scale, (ch) => (ch === 'X' ? colour : null));
  art(NINE, digitsX + 12 + dx, digitsY + dx, scale, (ch) => (ch === 'X' ? colour : null));
}

const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${GRID} ${GRID}" shape-rendering="crispEdges">
  <!-- Generated by scripts/make-app-icon.mjs: OSRS Strength icon + 99 -->
  ${rects.join('\n  ')}
</svg>
`;

fs.writeFileSync(path.join(process.cwd(), 'public/favicon.svg'), svg);
console.log('wrote public/favicon.svg');
